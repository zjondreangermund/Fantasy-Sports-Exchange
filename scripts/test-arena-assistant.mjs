import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
const temp=await mkdtemp(path.join(tmpdir(),'arena-support-'));
try{
await build({entryPoints:['server/services/arenaAssistant.ts','server/services/assistantPolicy.ts','server/services/supportWalletSnapshot.ts'],outdir:temp,outExtension:{'.js':'.mjs'},bundle:true,platform:'node',format:'esm'});
const {createArenaAssistant}=await import(path.join(temp,'arenaAssistant.mjs'));
const {scopedAssistantUser,assistantWindow,assistantTopics,assistantUserSearch,safeActivityPath,assistantRequestRefusal}=await import(path.join(temp,'assistantPolicy.mjs'));
const {supportWalletSnapshot}=await import(path.join(temp,'supportWalletSnapshot.mjs'));
assert.throws(()=>scopedAssistantUser('a',false,'b'),/administrators/);
assert.equal(scopedAssistantUser('admin',true,'b'),'b');
assert.equal(safeActivityPath('/wallet?token=secret#x'),'/wallet');
assert.equal(assistantUserSearch('What did Bob do while online?'),'Bob');
assert.equal(assistantUserSearch("Check Bob’s wallet"),'Bob');
assert.equal(assistantUserSearch('What did I do while online?'),'');
assert.equal(safeActivityPath('https://evil.test'),null);
assert.equal(safeActivityPath('/join/private-code'),'/join');
const now=new Date('2026-11-01T14:00:00Z');
assert.deepEqual(assistantWindow('today',undefined,now),{from:'2026-10-31T22:00:00.000Z',to:now.toISOString()});
assert.deepEqual(assistantWindow('yesterday',undefined,now),{from:'2026-10-30T22:00:00.000Z',to:'2026-10-31T22:00:00.000Z'});
assert.equal(assistantWindow('last month',undefined,now).from,'2026-09-30T22:00:00.000Z');
assert.throws(()=>assistantWindow('2026-02-30',undefined,now),/calendar/);
assert.throws(()=>assistantWindow('2026-01-01 to 2026-10-31',undefined,now),/90 days/);
assert.deepEqual(assistantTopics('and yesterday',['wallet']),['wallet']);
assert.deepEqual(assistantTopics('why is the sky blue',['wallet']),['help']);
assert.deepEqual(assistantTopics('why?',[]),['help']);
assert.ok(assistantTopics('Why can’t I enter a tournament?').includes('wallet'));
assert.deepEqual(assistantTopics('Please check the latest game week log'),['gameweek']);
assert.deepEqual(assistantTopics('Show GW9 log'),['gameweek']);
assert.match(assistantRequestRefusal('Can you enter a team for me').answer,/can’t choose or submit/);
assert.match(assistantRequestRefusal('Please settle tournament #5').answer,/can’t perform/);
assert.equal(assistantRequestRefusal('Why can’t I enter a tournament?'),null);
assert.equal(assistantRequestRefusal('Show my entries'),null);
let calls=[];
const q=async(sql,params=[])=>{
  calls.push({sql,params});
  if(sql.startsWith('SELECT id,name')&&sql.includes('ILIKE'))return [{id:'bob',name:'Bob'},{id:'bobby',name:'Bob'}];
  if(sql.startsWith('SELECT id,name'))return [{id:params[0],name:'Account'}];
  if(sql.includes('AS present'))return [{present:null}];
  if(sql.includes('AS escrow'))return [{escrow:null,holds:false}];
  if(sql.includes('FROM app.wallets WHERE user_id=$1'))return [{balance:12,lockedBalance:4}];
  if(sql.includes('AS "lastSeen"')&&sql.includes('WHERE user_id=$1'))return [{lastSeen:null,recentlyActive:false}];
  if(sql.includes('WITH first_seen'))return [{homepageViews:4,uniqueHomepageVisitors:3,firstSeenHomepageVisitors:2}];
  if(sql.includes('SELECT count(*)::int AS count FROM app.users'))return [{count:1}];
  if(sql.includes('SELECT min(created_at)'))return [{since:'2026-11-01'}];
  return [];
};
const answer=createArenaAssistant(q);
await assert.rejects(answer({actorId:'alice',admin:false,userId:'bob',question:'wallet'}),/administrators/);
await assert.rejects(answer({actorId:'alice',admin:false,question:'homepage visitors'}),/administrators/);
await assert.rejects(answer({actorId:'alice',admin:false,question:'and yesterday',previousTopics:['visitors']}),/administrators/);
await assert.rejects(answer({actorId:'alice',admin:false,userSearch:'Bob',question:'wallet'}),/administrators/);
calls=[];
let refused=await answer({actorId:'alice',admin:false,question:'Can you enter a team for me'});
assert.match(refused.answer,/can’t choose or submit/);assert.equal(refused.sections.length,0);assert.equal(calls.length,0);
let result=await answer({actorId:'alice',admin:false,question:'my wallet today'});
assert.equal(result.account.id,'alice');
assert.equal(result.sections.find(s=>s.title==='Current wallet').rows[0].balance,12);
assert(!result.answer.includes('wallet/ledger difference N$0.00')); // Unavailable reconciliation is not a zero delta.
for(const call of calls.filter(c=>/WHERE user_id=\$1/.test(c.sql)))assert.equal(call.params[0],'alice');
calls=[];
result=await answer({actorId:'admin',admin:true,userSearch:'Bob',question:'activity'});
assert.equal(result.candidates.length,2);assert(!calls.some(c=>c.sql.includes('FROM app.page_activity')));
result=await answer({actorId:'admin',admin:true,userSearch:'Bob',userId:'bob',question:'activity'});
assert.equal(result.account.id,'bob');
const injection="x%' OR true; --";
await answer({actorId:'admin',admin:true,userSearch:injection,question:'wallet'});
assert(calls.some(c=>c.params[0]===injection));assert(!calls.some(c=>c.sql.includes(injection)));
result=await answer({actorId:'admin',admin:true,question:'new users who visited the homepage today'});
assert.match(result.answer,/4 page views, 3 distinct browser visitors, 2 first seen/);
assert.match(result.answer,/1 accounts registered/);
const snapshot={balance:75,lockedBalance:25,totalDelta:0,lockedDelta:0,nonpostedNonzeroTransactions:0,withdrawalLedgerMismatches:0,auctionLedgerMismatches:0};
let report=await supportWalletSnapshot(async sql=>sql.includes('AS escrow')?[{escrow:'exists',holds:true}]:[snapshot],'alice');
assert.equal(report.status,'ok');
report=await supportWalletSnapshot(async sql=>sql.includes('AS escrow')?[{escrow:'exists',holds:true}]:[{...snapshot,totalDelta:12}],'alice');
assert.equal(report.status,'review');assert.match(report.flags,/wallet_ledger_difference/);
result=await answer({actorId:'alice',admin:false,question:'How do I choose a captain?'});
assert.match(result.answer,/10%/);assert.match(result.answer,/first Premier League kickoff/);
console.log('Assistant checks passed: account isolation, admin-only reports, name disambiguation, bound SQL, Namibia dates, honest missing evidence, visitor metrics, canonical help and wallet reconciliation.');
}finally{await rm(temp,{recursive:true,force:true});}
